def generate():
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        total = 0
        for cat, subs in categories.items():
            for sub in subs:
                f.write(f"КАТЕГОРИЯ: {cat}\n")
                f.write(f"  ПОДКАТЕГОРИЯ: {sub}\n")
                f.write("    ГРУППА: Разное\n")
                f.write("      ВИД: Разное\n")
                for i in range(55):
                    brand = random.choice(brands)
                    unit = random.choice(units)
                    base = random.choice(name_parts)
                    name = f"{base} {brand} {random.randint(100, 1000)}{unit}"
                    weight = f"{random.randint(100, 1000)} {unit}"
                    price = round(random.uniform(30, 800), 2)
                    cost = round(price * 0.7, 2)
                    nds = 20.00
                    barcode = f"460{random.randint(1000000000, 9999999999)}"
                    f.write(f"        БРЕНД: {brand}\n")
                    f.write(f"        ЕДИНИЦА: {unit}\n")
                    f.write(f"        ТОВАР: {name} | {weight} | {price} | {cost} | {nds} | {barcode}\n")
                    total += 1
                f.write("\n")
        print(f'Всего сгенерировано: {total}')


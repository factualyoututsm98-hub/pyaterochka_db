import random

OUTPUT = 'parsed_data.txt'

categories = {
    'Бакалея': ['Макароны, крупы', 'Мука, хлеб', 'Сахар, соль, специи'],
    'Молочная продукция': ['Молоко, сливки', 'Сыры', 'Творог, сметана', 'Йогурты'],
    'Мясо, птица': ['Мясо, птица', 'Колбасы', 'Сосиски', 'Полуфабрикаты'],
    'Рыба, морепродукты': ['Рыба', 'Морепродукты', 'Консервы рыбные'],
    'Овощи, фрукты': ['Овощи', 'Фрукты', 'Зелень', 'Орехи, сухофрукты'],
    'Напитки': ['Вода', 'Соки', 'Газировка', 'Чай, кофе'],
    'Сладости': ['Шоколад', 'Печенье', 'Торты', 'Мороженое'],
    'Снеки': ['Чипсы', 'Сухарики', 'Орешки'],
    'Замороженные': ['Пельмени', 'Блины', 'Овощи замороженные'],
    'Для животных': ['Для кошек', 'Для собак'],
}

brands = ['Makfa', 'Barilla', 'Простоквашино', 'Мираторг', 'Сады Придонья',
          'Milka', 'Черкизово', 'Вкусно и точка', 'Красная цена', 'Выручай',
          'Global Village', 'Мистраль', 'Увелка', 'Шебекинские', 'BeFresh']

units = ['г', 'кг', 'мл', 'л', 'шт']

name_parts = ['Спагетти', 'Рис', 'Макароны', 'Молоко', 'Сыр', 'Творог', 'Йогурт',
              'Курица', 'Свинина', 'Говядина', 'Колбаса', 'Сосиски', 'Рыба',
              'Сельдь', 'Овощи', 'Фрукты', 'Яблоки', 'Бананы', 'Вода', 'Сок',
              'Чай', 'Кофе', 'Шоколад', 'Печенье', 'Чипсы', 'Пельмени', 'Блины',
              'Корм для кошек', 'Корм для собак']

def generate():
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        for cat, subs in categories.items():
            for sub in subs:
                f.write(f"КАТЕГОРИЯ: {cat}\n")
                f.write(f"  ПОДКАТЕГОРИЯ: {sub}\n")
                f.write("    ГРУППА: Разное\n")
                f.write("      ВИД: Разное\n")
                for i in range(random.randint(8, 15)):
                    brand = random.choice(brands)
                    unit = random.choice(units)
                    base = random.choice(name_parts)
                    name = f"{base} {brand} {random.randint(100, 1000)}{unit}"
                    weight = f"{random.randint(100, 1000)} {unit}"
                    price = round(random.uniform(30, 800), 2)
                    cost = round(price * 0.7, 2)
                    nds = 20.00
                    barcode = f"460{random.randint(1000000000, 9999999999)}"
                    f.write(f"        БРЕНД: {brand}\n")
                    f.write(f"        ЕДИНИЦА: {unit}\n")
                    f.write(f"        ТОВАР: {name} | {weight} | {price} | {cost} | {nds} | {barcode}\n")
                f.write("\n")

if __name__ == '__main__':
    generate()
    print('Готово! Данные сгенерированы в parsed_data.txt')